    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String usuario = jTextField1.getText().trim();
        String senha = new String(jPasswordField1.getPassword());

    if (usuario.isEmpty() || senha.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Informe o usuário e a senha.",
                "Atenção",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "SELECT id_funcionario, nome_funcionario, "
        + "cargo_funcionario, grauacesso_usuario_func "
        + "FROM funcionarios "
        + "WHERE nome_usuario_func = ? "
        + "AND senha_usuario_func = ?";

    try {

        pst = conexao.prepareStatement(sql);

        pst.setString(1, usuario);
        pst.setString(2, senha);

        rs = pst.executeQuery();

        if (rs.next()) {

            int id = rs.getInt("id_funcionario");
            String nome = rs.getString("nome_funcionario");
            String grau = rs.getString("grauacesso_usuario_func");

            // Guarda os dados do usuário que entrou
            SessaoUsuario.iniciarSessao(
                rs.getInt("id_funcionario"),
                rs.getString("nome_funcionario"),
                rs.getString("cargo_funcionario"),
                rs.getString("grauacesso_usuario_func")
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Bem-vindo(a), " + nome + "!\n"
                    + "Grau de acesso: " + grau
            );

            TelaPrincipal tela = new TelaPrincipal();
            tela.setVisible(true);

            // Fecha a tela de login
            this.dispose();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Usuário ou senha incorretos.",
                    "Erro de Login",
                    JOptionPane.ERROR_MESSAGE
            );

            jPasswordField1.setText("");
            jTextField1.requestFocus();

        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Erro ao realizar login:\n" + e.getMessage(),
                "Erro",
                JOptionPane.ERROR_MESSAGE
        );

    } finally {

        try {
            if (rs != null) {
                rs.close();
            }

            if (pst != null) {
                pst.close();
            }

        } catch (SQLException e) {
            System.out.println("Erro ao fechar conexão: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_jButton2ActionPerformed

